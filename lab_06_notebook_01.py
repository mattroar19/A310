"""Histograms are used to visualized sampled data and show the shape of distribution."""

np.random.seed(0)
sample_size = 10000
sample_means = np.random.binomial(sample_size, 0.5, 100000) / sample_size

plt.hist(sample_means, bins='auto', edgecolor='black', density=True)
plt.xlabel('Binned Sample Mean')
plt.ylabel('Relative Likelihood')
plt.title('Histogram of Sample Means')
plt.show()

