import numpy as np
import matplotlib.pyplot as plt
from scipy import stats

"""A line plot is used to show how probability chages across possible head counts"""

num_flips = 20
prob_head = 0.5
x_values = range(num_flips + 1)
y_values = stats.binom.pmf(x_values, num_flips, prob_head)

plt.plot(x_values, y_values)
plt.xlabel('Head-count')
plt.ylabel('Probability')
plt.title('Line Plot of Binomial Probabilities')
plt.show()

